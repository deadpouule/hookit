function PixelGlyph({ art }: { art: readonly string[] }) {
  const height = art.length;
  const width = Math.max(...art.map((row) => row.length));
  const rects: ReactNode[] = [];

  art.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const cell = row[x];
      if (cell === "." || cell === " ") {
        x += 1;
        continue;
      }
      let x2 = x + 1;
      while (x2 < row.length && row[x2] === cell) x2 += 1;
      rects.push(
        <rect
          key={`${x}-${y}`}
          x={x}
          y={y}
          width={x2 - x}
          height={1}
          fill="currentColor"
          fillOpacity={cell === "o" ? 0.35 : undefined}
        />,
      );
      x = x2;
    }
  });

  return (
    <svg viewBox={`0 0 ${width} ${height}`} shapeRendering="crispEdges" aria-hidden>
      {rects}
    </svg>
  );
}

export function HookLogo({
  hookId,
  theme,
  className,
}: {
  hookId: BrowseHookId;
  theme: HookTheme;
  className?: string;
}) {
  return (
    <span className={cn("hook-logo", `hook-logo--${theme}`, className)} aria-hidden>
      <PixelGlyph art={PIXEL_ART[hookId]} />
    </span>
  );
}
